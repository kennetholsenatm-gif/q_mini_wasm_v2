// Managed Go HTTP infer stub for trained artifacts (POST /api/serve/*).
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"sync"
	"time"
)

type serveInstance struct {
	embed     *embeddedInferServer
	modelStem string
	port      int
	started   time.Time
	logBuf    *bytes.Buffer
}

var (
	serveMu     sync.Mutex
	serveActive *serveInstance
)

func serveProcessRunning() bool {
	serveMu.Lock()
	defer serveMu.Unlock()
	return serveActive != nil
}

func anyTrainingRunActive() bool {
	runManager.mu.Lock()
	defer runManager.mu.Unlock()
	for _, id := range runManager.ordered {
		if r := runManager.byID[id]; r != nil && r.Running {
			return true
		}
	}
	return false
}

func writeDockerComposeServe(stem string, port int) (relPath string, err error) {
	stem = strings.TrimSpace(stem)
	if stem == "" {
		return "", errors.New("model stem is required")
	}
	dir := filepath.Join(repoRoot, filepath.FromSlash(artifactModelDir(stem)))
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	serveRel := filepath.ToSlash(filepath.Join(artifactModelDir(stem), "serve.toml"))
	portStr := strconv.Itoa(port)
	// Run from repository root so the bind mount resolves correctly.
	body := fmt.Sprintf(`# Generated by training-wui. From repository root:
#   docker compose -f %s up
# Uses Go qmw-serve (no Python). First start may download modules.
services:
  qminiwasm-serve:
    image: golang:1.22-bookworm
    working_dir: /repo/training-wui
    volumes:
      - .:/repo
    ports:
      - "%s:%s"
    environment:
      QMINIWASM_SERVE_CONFIG: /repo/%s
    command: >-
      sh -c "go run ./cmd/qmw-serve -listen 0.0.0.0:%s -config /repo/%s"
`,
		filepath.ToSlash(filepath.Join(artifactModelDir(stem), "docker-compose.serve.yaml")),
		portStr, portStr,
		serveRel,
		portStr,
		serveRel,
	)
	outPath := filepath.Join(dir, "docker-compose.serve.yaml")
	if err := os.WriteFile(outPath, []byte(body), 0o644); err != nil {
		return "", err
	}
	return filepath.ToSlash(filepath.Join(artifactModelDir(stem), "docker-compose.serve.yaml")), nil
}

func handleServeStart(w http.ResponseWriter, r *http.Request) {
	if !authOK(r) {
		http.Error(w, "unauthorized", http.StatusUnauthorized)
		return
	}
	if r.Method != http.MethodPost {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	if anyTrainingRunActive() {
		jsonErr(w, http.StatusConflict, "stop the active training run before starting the serve process")
		return
	}
	var body struct {
		ModelStem string `json:"model_stem"`
		Port      int    `json:"port"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		jsonErr(w, http.StatusBadRequest, "invalid JSON")
		return
	}
	stem := strings.TrimSpace(body.ModelStem)
	if stem == "" {
		jsonErr(w, http.StatusBadRequest, "model_stem is required")
		return
	}
	port := body.Port
	if port <= 0 {
		port = 8001
	}
	bundleAbs := filepath.Join(repoRoot, filepath.FromSlash(artifactModelDir(stem)), "agent_bundle.json")
	serveAbs := filepath.Join(repoRoot, filepath.FromSlash(artifactModelDir(stem)), "serve.toml")
	if _, err := os.Stat(bundleAbs); err != nil {
		jsonErr(w, http.StatusBadRequest, "agent_bundle.json not found — save working config from the wizard first")
		return
	}
	if _, err := os.Stat(serveAbs); err != nil {
		jsonErr(w, http.StatusBadRequest, "serve.toml not found — save working config from the wizard first")
		return
	}

	composeRel, werr := writeDockerComposeServe(stem, port)
	if werr != nil {
		jsonErr(w, http.StatusInternalServerError, werr.Error())
		return
	}

	serveMu.Lock()
	if serveActive != nil {
		serveMu.Unlock()
		jsonErr(w, http.StatusConflict, "serve process already running — call /api/serve/stop first")
		return
	}
	emb := &embeddedInferServer{}
	if err := emb.start(port, stem, serveAbs); err != nil {
		serveMu.Unlock()
		jsonErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	logBuf := &bytes.Buffer{}
	_, _ = logBuf.WriteString("embedded Go infer server (GET /health, POST /infer stub)\n")
	serveActive = &serveInstance{
		embed:     emb,
		modelStem: stem,
		port:      port,
		started:   time.Now(),
		logBuf:    logBuf,
	}
	serveMu.Unlock()

	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(map[string]any{
		"ok":             true,
		"model_stem":     stem,
		"port":           port,
		"runtime":        "go",
		"health_url":     fmt.Sprintf("http://127.0.0.1:%d/health", port),
		"docker_compose": composeRel,
	})
}

func handleServeStop(w http.ResponseWriter, r *http.Request) {
	if !authOK(r) {
		http.Error(w, "unauthorized", http.StatusUnauthorized)
		return
	}
	if r.Method != http.MethodPost {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	serveMu.Lock()
	si := serveActive
	serveActive = nil
	serveMu.Unlock()
	if si == nil || si.embed == nil {
		jsonErr(w, http.StatusNotFound, "no serve process")
		return
	}
	_ = si.embed.stop()
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(map[string]any{"ok": true})
}

func handleServeStatus(w http.ResponseWriter, r *http.Request) {
	if !authOK(r) {
		http.Error(w, "unauthorized", http.StatusUnauthorized)
		return
	}
	if r.Method != http.MethodGet {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	serveMu.Lock()
	si := serveActive
	serveMu.Unlock()
	if si == nil {
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(map[string]any{"running": false})
		return
	}
	tail := ""
	if si.logBuf != nil {
		tail = si.logBuf.String()
	}
	if len(tail) > 4000 {
		tail = tail[len(tail)-4000:]
	}
	out := map[string]any{
		"running":    true,
		"model_stem": si.modelStem,
		"port":       si.port,
		"started":    si.started.Format(time.RFC3339),
		"log_tail":   tail,
	}
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(out)
}
