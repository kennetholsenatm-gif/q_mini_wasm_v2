// GetTestSummary returns summary of all test results
func (t *TestAgent) GetTestSummary() map[string]interface{} {
	totalTests := 0
	totalPassed := 0
	totalFailed := 0
	totalSkipped := 0

	for _, result := range t.TestResults {
		totalTests += result.TotalTests
		totalPassed += result.Passed
		totalFailed += result.Failed
		totalSkipped += result.Skipped
	}

	passRate := 0.0
	if totalTests > 0 {
		passRate = float64(totalPassed) / float64(totalTests) * 100
	}

	return map[string]interface{}{
		"total_tests":   totalTests,
		"passed":        totalPassed,
		"failed":        totalFailed,
		"skipped":       totalSkipped,
		"pass_rate":     fmt.Sprintf("%.2f%%", passRate),
		"test_files":    len(t.TestResults),
		"supported_langs": t.SupportedLangs,
		"frameworks":    t.TestFrameworks,
	}
}

// GetTestConfig returns test configuration for a language
func (t *TestAgent) GetTestConfig(language string, sourceFile string) (*TestConfig, error) {
	config := &TestConfig{
		Language:   language,
		SourceFile: sourceFile,
	}

	switch language {
	case "C++":
		config.TestFile = strings.TrimSuffix(sourceFile, filepath.Ext(sourceFile)) + "_test.cpp"
		config.TestFramework = "Catch2"
		config.BuildCommand = "g++ -std=c++17 -o test_runner " + config.TestFile
		config.RunCommand = "./test_runner"
	case "Go":
		config.TestFile = strings.TrimSuffix(sourceFile, filepath.Ext(sourceFile)) + "_test.go"
		config.TestFramework = "testing"
		config.BuildCommand = "go test -c"
		config.RunCommand = "go test -v"
	case "R":
		config.TestFile = "tests/testthat.R"
		config.TestFramework = "testthat"
		config.BuildCommand = ""
		config.RunCommand = "Rscript -e 'testthat::test_dir(\"tests\")'"
	case "Python":
		config.TestFile = "tests/test_" + filepath.Base(sourceFile)
		config.TestFramework = "pytest"
		config.BuildCommand = ""
		config.RunCommand = "pytest -v " + config.TestFile
	default:
		return nil, fmt.Errorf("unsupported language: %s", language)
	}

	return config, nil
}

func main() {
	agent := NewTestAgent()

	if len(os.Args) > 1 {
		command := os.Args[1]

		switch command {
		case "generate":
			if len(os.Args) < 4 {
				fmt.Println("Usage: test-agent generate <source-file> <language>")
				os.Exit(1)
			}
			sourceFile := os.Args[2]
			language := os.Args[3]

			testCode, err := agent.GenerateTests(sourceFile, language)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error: %v\n", err)
				os.Exit(1)
			}
			fmt.Println(testCode)

		case "run":
			if len(os.Args) < 4 {
				fmt.Println("Usage: test-agent run <test-file> <language>")
				os.Exit(1)
			}
			testFile := os.Args[2]
			language := os.Args[3]

			result, err := agent.RunTests(testFile, language)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error: %v\n", err)
				os.Exit(1)
			}
			json.NewEncoder(os.Stdout).Encode(result)

		case "config":
			if len(os.Args) < 4 {
				fmt.Println("Usage: test-agent config <source-file> <language>")
				os.Exit(1)
			}
			sourceFile := os.Args[2]
			language := os.Args[3]

			config, err := agent.GetTestConfig(language, sourceFile)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error: %v\n", err)
				os.Exit(1)
			}
			json.NewEncoder(os.Stdout).Encode(config)

		case "summary":
			summary := agent.GetTestSummary()
			json.NewEncoder(os.Stdout).Encode(summary)

		default:
			fmt.Println("Test Agent - Test Generation and Execution")
			fmt.Println("Supported languages:", strings.Join(agent.SupportedLangs, ", "))
			fmt.Println("Test frameworks:", agent.TestFrameworks)
			fmt.Println("\nCommands:")
			fmt.Println("  generate <source> <lang>  - Generate tests for source file")
			fmt.Println("  run <test-file> <lang>    - Run tests")
			fmt.Println("  config <source> <lang>    - Get test configuration")
			fmt.Println("  summary                   - Get test summary")
		}
	} else {
		fmt.Println("Test Agent - Test Generation and Execution")
		fmt.Println("Supported languages:", strings.Join(agent.SupportedLangs, ", "))
		fmt.Println("\nUsage: test-agent <command> [args]")
	}
}

